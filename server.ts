let autoClockOutRunning = false;

setInterval(async () => {
  if (autoClockOutRunning) return;

  const now = new Date();
  if (now.getHours() === 23 && now.getMinutes() === 59) {
    autoClockOutRunning = true;

    try {
      const result = await pool.query(
        "SELECT id, organization_id FROM users WHERE status = 'in' AND active = 1 AND role = 'staff'"
      );

      for (const emp of result.rows) {
        const timestamp = new Date().toISOString();

        await pool.query(
          `
          INSERT INTO shifts (organization_id, employee_id, type, timestamp, photo, latitude, longitude)
          VALUES ($1, $2, $3, $4, $5, $6, $7)
          `,
          [emp.organization_id, emp.id, "out", timestamp, "AUTO_CLOCK_OUT", 0, 0]
        );

        await pool.query(
          "UPDATE users SET status = 'out' WHERE id = $1",
          [emp.id]
        );
      }
    } catch (error) {
      console.error("[AUTO CLOCK-OUT ERROR]", error);
    } finally {
      autoClockOutRunning = false;
    }
  }
}, 60000);

