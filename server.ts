async function initPostgres() {
  // Ensure plain_password column exists
  try {
    await pool.query("ALTER TABLE users ADD COLUMN IF NOT EXISTS plain_password TEXT");
  } catch (e) {
    // Ignore if already exists or other error
  }

  // Organizations
  await pool.query(`
    CREATE TABLE IF NOT EXISTS organizations (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name TEXT NOT NULL,
      slug TEXT UNIQUE NOT NULL,
      status TEXT NOT NULL DEFAULT 'active',
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);

  // Organization Settings
  await pool.query(`
    CREATE TABLE IF NOT EXISTS organization_settings (
      organization_id BIGINT PRIMARY KEY REFERENCES organizations(id) ON DELETE CASCADE,
      labels JSONB NOT NULL DEFAULT '{"staff": "Staff", "clockIn": "Clock In", "clockOut": "Clock Out", "location": "Location"}',
      branding JSONB NOT NULL DEFAULT '{"primaryColor": "#10b981"}',
      features JSONB NOT NULL DEFAULT '{"photoRequired": true, "geofencing": true, "pinLogin": true}',
      google_sheets_token TEXT,
      admin_email TEXT,
      admin_password TEXT
    );
  `);

  // Locations
  await pool.query(`
    CREATE TABLE IF NOT EXISTS locations (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      address TEXT,
      latitude DOUBLE PRECISION NOT NULL,
      longitude DOUBLE PRECISION NOT NULL,
      radius_meters INTEGER NOT NULL DEFAULT 100
    );
  `);

  // Users (Refactored from employees)
  await pool.query(`
    CREATE TABLE IF NOT EXISTS users (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      organization_id BIGINT REFERENCES organizations(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      email TEXT,
      role TEXT NOT NULL DEFAULT 'staff',
      pin TEXT,
      status TEXT NOT NULL DEFAULT 'out',
      active INTEGER NOT NULL DEFAULT 1,
      password TEXT,
      plain_password TEXT
    );
  `);

  // Invites
  await pool.query(`
    CREATE TABLE IF NOT EXISTS invites (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      email TEXT NOT NULL,
      token TEXT UNIQUE NOT NULL,
      expires_at TIMESTAMPTZ NOT NULL,
      accepted_at TIMESTAMPTZ,
      created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
    );
  `);

  // Shifts
  await pool.query(`
    CREATE TABLE IF NOT EXISTS shifts (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      organization_id BIGINT NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
      employee_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      location_id BIGINT REFERENCES locations(id) ON DELETE SET NULL,
      type TEXT NOT NULL,
      timestamp TIMESTAMPTZ NOT NULL,
      photo TEXT NOT NULL,
      latitude DOUBLE PRECISION,
      longitude DOUBLE PRECISION
    );
  `);

  // Global Settings (for Super Admin)
  await pool.query(`
    CREATE TABLE IF NOT EXISTS settings (
      key TEXT PRIMARY KEY,
      value TEXT
    );
  `);

  // Migration: Move data from old tables if they exist
  try {
    const tableCheck = await pool.query("SELECT to_regclass('employees')");
    if (tableCheck.rows[0].to_regclass) {
      const orgCheck = await pool.query("SELECT id FROM organizations WHERE slug = 'default'");
      let defaultOrgId;
      if (orgCheck.rows.length === 0) {
        const newOrg = await pool.query(
          "INSERT INTO organizations (name, slug) VALUES ($1, $2) RETURNING id",
          ["Default Organization", "default"]
        );
        defaultOrgId = newOrg.rows[0].id;
        
        // Seed default settings
        const oldSettings = await getAllSettings();
        await pool.query(
          `INSERT INTO organization_settings (organization_id, admin_email, admin_password, google_sheets_token)
           VALUES ($1, $2, $3, $4)`,
          [defaultOrgId, oldSettings.admin_email || 'admin@example.com', oldSettings.admin_password || hashValue('admin123'), oldSettings.google_sheets_token || '']
        );

        // Create default location
        await pool.query(
          `INSERT INTO locations (organization_id, name, latitude, longitude, radius_meters)
           VALUES ($1, $2, $3, $4, $5)`,
          [defaultOrgId, "Main Office", parseFloat(oldSettings.restaurant_lat || "0"), parseFloat(oldSettings.restaurant_lng || "0"), parseInt(oldSettings.allowed_radius || "100")]
        );
      } else {
        defaultOrgId = orgCheck.rows[0].id;
      }

      // Migrate employees to users
      await pool.query(`
        INSERT INTO users (id, organization_id, name, role, pin, status, active)
        SELECT id, ${defaultOrgId}, name, 'staff', pin, status, active FROM employees
        ON CONFLICT (id) DO NOTHING
      `);

      // Migrate shifts
      await pool.query(`
        INSERT INTO shifts (id, organization_id, employee_id, type, timestamp, photo, latitude, longitude)
        SELECT id, ${defaultOrgId}, employee_id, type, timestamp, photo, latitude, longitude FROM shifts
        ON CONFLICT (id) DO NOTHING
      `);

      // Drop old tables after migration (optional, but safer to keep for a bit)
      // await pool.query("DROP TABLE employees, shifts CASCADE");
    }
  } catch (e) {
    console.error("Migration error:", e);
  }
}

